def test_discrete_frechet_detour_costs_the_detour_exactly():
    # A = 0, 1, 2 ; B = 0, 1, 100, 2.
    # The vertex B[2] = 100 must be coupled to some A vertex. The three
    # candidate distances are |0-100| = 100, |1-100| = 99, |2-100| = 98, so the
    # cheapest coupling pairs it with A[2] = 2 and pays exactly 98. Every other
    # pair in that coupling ((0,0), (1,1), (2,2), (2,3)) costs at most 1.
    a = np.array([[0.0], [1.0], [2.0]])
    b = np.array([[0.0], [1.0], [100.0], [2.0]])
    assert discrete_frechet(a, b) == 98.0


def test_discrete_frechet_of_a_curve_with_itself_is_zero():
    rng = np.random.default_rng(SEED + 1)
    for k in (1, 2, 5, 9):
        for d in (1, 2, 3):
            curve = _random_curve(rng, k, d)
            assert discrete_frechet(curve, curve) == 0.0


def test_discrete_frechet_is_symmetric_on_random_pairs():
    for a, b in RANDOM_PAIRS:
        assert discrete_frechet(a, b) == discrete_frechet(b, a)  # bit-exact


def test_discrete_frechet_is_at_least_the_endpoint_distances():
    # Every coupling contains (0, 0) and (m-1, n-1), so its max is at least
    # each of those two distances.
    for a, b in RANDOM_PAIRS:
        endpoint_bound = max(
            float(np.linalg.norm(a[0] - b[0])),
            float(np.linalg.norm(a[-1] - b[-1])),
        )
        assert discrete_frechet(a, b) >= endpoint_bound - 1e-12


def test_discrete_frechet_matches_brute_force_coupling_enumeration():
    rng = np.random.default_rng(SEED + 2)
    for _ in range(25):
        d = int(rng.integers(1, 4))
        m = int(rng.integers(1, 6))
        n = int(rng.integers(1, 6))
        a = _random_curve(rng, m, d)
        b = _random_curve(rng, n, d)
        assert discrete_frechet(a, b) == pytest.approx(
            _brute_discrete_frechet(a, b), rel=0.0, abs=1e-12
        )


def test_discrete_frechet_rejects_nan_and_ragged_input():
    good = np.array([[0.0], [1.0]])
    with pytest.raises(ValueError):
        discrete_frechet(np.array([[0.0], [np.nan]]), good)
    with pytest.raises(ValueError):
        discrete_frechet(np.array([[0.0], [np.inf]]), good)
    with pytest.raises(ValueError):
        discrete_frechet(np.zeros((0, 1)), good)
    with pytest.raises(ValueError):
        discrete_frechet(np.array([[0.0, 1.0]]), good)  # mismatched dimension


