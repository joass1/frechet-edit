def test_dtw_of_a_curve_with_itself_is_zero():
    rng = np.random.default_rng(SEED + 3)
    for k in (1, 3, 8):
        curve = _random_curve(rng, k, 2)
        assert dtw(curve, curve) == 0.0
        assert dtw_normalized(curve, curve) == 0.0


def test_dtw_is_at_most_the_pointwise_sum_for_equal_lengths():
    # The strictly diagonal warping path is legal whenever m == n, and its cost
    # is exactly the sum of the pointwise distances; DTW is the minimum over
    # all paths, so it can only be smaller.
    rng = np.random.default_rng(SEED + 4)
    for _ in range(20):
        k = int(rng.integers(1, 10))
        d = int(rng.integers(1, 4))
        a = _random_curve(rng, k, d)
        b = _random_curve(rng, k, d)
        assert dtw(a, b) <= float(np.sum(_pointwise_distances(a, b))) + 1e-12


def test_dtw_is_symmetric_and_nonnegative():
    for a, b in RANDOM_PAIRS:
        forward = dtw(a, b)
        assert forward >= 0.0
        assert forward == pytest.approx(dtw(b, a), rel=0.0, abs=1e-12)


def test_dtw_normalized_is_a_different_measure_from_dtw():
    # Same normalised cost, different raw cost: a constant per-pair offset of 1
    # over paths of different lengths. This is the concrete reason the two must
    # be reported in separate columns.
    short_a = np.array([[0.0], [0.0]])
    short_b = np.array([[1.0], [1.0]])
    long_a = np.array([[0.0]] * 6)
    long_b = np.array([[1.0]] * 6)

    assert dtw(short_a, short_b) == pytest.approx(2.0)
    assert dtw(long_a, long_b) == pytest.approx(6.0)
    assert dtw_normalized(short_a, short_b) == pytest.approx(1.0)
    assert dtw_normalized(long_a, long_b) == pytest.approx(1.0)
    assert dtw(short_a, short_b) != pytest.approx(dtw(long_a, long_b))


