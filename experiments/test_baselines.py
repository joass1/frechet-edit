def test_enumerate_couplings_is_itself_sane():
    # Guard the test helper: the number of monotone lattice paths with the
    # three allowed moves from (0,0) to (m-1,n-1) is the Delannoy number
    # D(m-1, n-1). D(1,1) = 3, D(2,2) = 13, D(3,3) = 63.
    assert len(list(_enumerate_couplings(2, 2))) == 3
    assert len(list(_enumerate_couplings(3, 3))) == 13
    assert len(list(_enumerate_couplings(4, 4))) == 63
    # Every enumerated coupling must be legal.
    for coupling in itertools.islice(_enumerate_couplings(4, 3), 100):
        assert coupling[0] == (0, 0)
        assert coupling[-1] == (3, 2)
        for (i0, j0), (i1, j1) in itertools.pairwise(coupling):
            assert (i1 - i0, j1 - j0) in {(1, 0), (0, 1), (1, 1)}
