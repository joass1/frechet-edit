def test_continuous_frechet_of_parallel_unit_segments_offset_by_half():
    # Two unit segments, one directly above the other at distance 0.5. The
    # natural parameterisation holds the distance at exactly 0.5 everywhere,
    # and the endpoints are 0.5 apart, so no traversal can do better.
    a = np.array([[0.0, 0.0], [1.0, 0.0]])
    b = np.array([[0.0, 0.5], [1.0, 0.5]])
    assert continuous_frechet(a, b) == pytest.approx(0.5, abs=1e-9)


def test_continuous_frechet_never_exceeds_discrete_frechet():
    for a, b in RANDOM_PAIRS:
        assert continuous_frechet(a, b) <= discrete_frechet(a, b)


def test_continuous_and_discrete_agree_for_two_two_point_segments():
    # For two single segments the distance ||A(t) - B(t)|| under the linear
    # parameterisation is the norm of an affine function of t, hence convex, so
    # its maximum on [0, 1] is attained at an endpoint. Both the continuous and
    # the discrete value therefore equal max(||A0-B0||, ||A1-B1||).
    cases = [
        # matching (shared) endpoints -> both are 0
        (np.array([[0.0, 0.0], [1.0, 0.0]]), np.array([[0.0, 0.0], [1.0, 0.0]])),
        # translated segment
        (np.array([[0.0, 0.0], [1.0, 0.0]]), np.array([[0.0, 1.0], [2.0, 1.0]])),
        # crossing segments
        (np.array([[0.0, 0.0], [2.0, 2.0]]), np.array([[0.0, 2.0], [2.0, 0.0]])),
    ]
    for a, b in cases:
        expected = max(
            float(np.linalg.norm(a[0] - b[0])), float(np.linalg.norm(a[1] - b[1]))
        )
        assert discrete_frechet(a, b) == pytest.approx(expected, abs=1e-12)
        assert continuous_frechet(a, b) == pytest.approx(expected, abs=1e-9)


def test_continuous_frechet_beats_discrete_when_interpolation_helps():
    # Construction: A is the straight segment (0,0) -> (10,0); B is the same
    # journey with a detour through the apex (5,1).
    #
    # DISCRETE: the apex B[1] = (5,1) can only be coupled to a VERTEX of A, and
    # both are sqrt((5)^2 + 1) = sqrt(26) ~ 5.0990 away, so the discrete value
    # is sqrt(26).
    # CONTINUOUS: the apex may be matched to the INTERIOR point (5,0) of A's
    # single segment, at distance 1. Matching every B point (x, y) to (x, 0)
    # is monotone and never exceeds the apex height 1, and no eps < 1 works
    # because the apex is 1 away from the whole of A. So the value is exactly 1.
    a = np.array([[0.0, 0.0], [10.0, 0.0]])
    b = np.array([[0.0, 0.0], [5.0, 1.0], [10.0, 0.0]])

    assert discrete_frechet(a, b) == pytest.approx(math.sqrt(26.0), abs=1e-12)
    value = continuous_frechet(a, b)
    assert value == pytest.approx(1.0, abs=1e-8)
    assert value < discrete_frechet(a, b) - 1e-6


def test_continuous_frechet_matches_a_densified_discrete_approximation():
    # Independent check on the whole Alt-Godau path: refine both curves until
    # consecutive samples are h apart, then run the (separately tested)
    # discrete DP. The refined discrete value sandwiches the continuous one:
    #   continuous <= densified_discrete <= continuous + h.
    for a, b in SHARED_ENDPOINT_PAIRS:
        value = continuous_frechet(a, b)
        dense_a = _densify(a, 60)
        dense_b = _densify(b, 60)
        refined = discrete_frechet(dense_a, dense_b)
        h = max(_max_step(dense_a), _max_step(dense_b))
        assert value <= refined + 1e-9
        assert refined - value <= h + 1e-9


def test_continuous_frechet_is_strictly_smaller_when_the_optimum_is_interior():
    # Curves sharing both endpoints but wandering in between: the discrete
    # value is forced onto vertex-to-vertex pairs, the continuous one is not.
    for a, b in SHARED_ENDPOINT_PAIRS:
        assert continuous_frechet(a, b) < discrete_frechet(a, b)


def test_continuous_frechet_corner_versus_diagonal_closed_form():
    # A traces two sides of the unit square, B its diagonal. The corner (1,0)
    # must be matched somewhere on the diagonal; its nearest diagonal point is
    # (0.5, 0.5), at distance 1/sqrt(2), and that matching extends monotonically
    # to the whole traversal. The discrete value instead has to pair (1,0) with
    # a diagonal VERTEX, both at distance 1.
    a = np.array([[0.0, 0.0], [1.0, 0.0], [1.0, 1.0]])
    b = np.array([[0.0, 0.0], [1.0, 1.0]])
    assert continuous_frechet(a, b) == pytest.approx(1.0 / math.sqrt(2.0), abs=1e-8)
    assert discrete_frechet(a, b) == pytest.approx(1.0, abs=1e-12)


def test_continuous_frechet_le_is_a_closed_monotone_decision():
    a = np.array([[0.0, 0.0], [10.0, 0.0]])
    b = np.array([[0.0, 0.0], [5.0, 1.0], [10.0, 0.0]])
    assert continuous_frechet_le(a, b, 1.0) is True
    assert continuous_frechet_le(a, b, 1.5) is True
    assert continuous_frechet_le(a, b, 0.999) is False
    assert continuous_frechet_le(a, b, 0.0) is False


def test_continuous_frechet_le_enforces_the_endpoint_rule():
    # The curves overlap almost everywhere but their final vertices are 5
    # apart, so no eps below 5 can be feasible however close the rest is.
    a = np.array([[0.0, 0.0], [1.0, 0.0], [2.0, 0.0]])
    b = np.array([[0.0, 0.0], [1.0, 0.0], [2.0, 5.0]])
    assert continuous_frechet_le(a, b, 4.9) is False
    assert continuous_frechet_le(a, b, 5.0) is True
    assert continuous_frechet(a, b) == pytest.approx(5.0, abs=1e-9)


def test_continuous_frechet_handles_single_point_curves():
    # A single point against a polyline: the value is the largest distance to
    # any point of the polyline, attained at a vertex by convexity.
    a = np.array([[0.0, 0.0]])
    b = np.array([[0.0, 0.0], [3.0, 4.0], [0.0, 1.0]])
    with pytest.raises(ValueError):
        continuous_frechet_le(a, b, -1.0)
    assert continuous_frechet_le(a, b, 5.0) is True
    assert continuous_frechet_le(a, b, 4.9) is False
    assert continuous_frechet(a, b) == pytest.approx(5.0, abs=1e-9)


