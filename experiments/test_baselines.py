def test_edr_of_a_curve_with_itself_is_zero():
    rng = np.random.default_rng(SEED + 5)
    for eps in (0.0, 0.5, 3.0):
        for k in (1, 4, 9):
            curve = _random_curve(rng, k, 2)
            assert edr(curve, curve, eps) == 0


def test_edr_is_symmetric():
    for a, b in RANDOM_PAIRS:
        for eps in (0.0, 1.0, 4.0):
            assert edr(a, b, eps) == edr(b, a, eps)


def test_edr_never_exceeds_the_longer_length():
    for a, b in RANDOM_PAIRS:
        for eps in (0.0, 0.25, 2.0):
            assert 0 <= edr(a, b, eps) <= max(len(a), len(b))


def test_edr_with_zero_eps_on_disjoint_curves_is_the_longer_length():
    # With eps = 0 and no coincident points, every substitution costs 1 and so
    # does every gap, which is Levenshtein distance over disjoint alphabets:
    # exactly max(m, n).
    a = np.array([[0.0], [1.0], [2.0], [3.0], [4.0]])
    b = np.array([[10.0], [11.0], [12.0]])
    assert edr(a, b, 0.0) == 5
    assert edr(b, a, 0.0) == 5

    c = np.array([[0.0, 0.0], [1.0, 1.0]])
    e = np.array([[7.0, 7.0], [8.0, 8.0], [9.0, 9.0], [10.0, 10.0]])
    assert edr(c, e, 0.0) == 4


def test_edr_returns_a_python_int():
    a = np.array([[0.0], [1.0]])
    b = np.array([[0.0], [5.0]])
    assert isinstance(edr(a, b, 0.5), int)


