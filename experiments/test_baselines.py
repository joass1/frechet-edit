FILTERS = [moving_average_filter, median_filter]


@pytest.mark.parametrize("filter_fn", FILTERS)
def test_filter_preserves_the_number_of_points(filter_fn):
    rng = np.random.default_rng(SEED + 9)
    for k in (1, 2, 3, 8, 15):
        for window in (1, 3, 5, 9):
            curve = _random_curve(rng, k, 2)
            out = filter_fn(curve, window)
            assert out.shape == curve.shape
            assert out.dtype == np.float64


@pytest.mark.parametrize("filter_fn", FILTERS)
def test_filter_leaves_a_constant_signal_unchanged(filter_fn):
    curve = np.tile(np.array([[2.0, -7.0]]), (11, 1))
    for window in (1, 3, 5, 11):
        np.testing.assert_allclose(filter_fn(curve, window), curve, atol=1e-12)


@pytest.mark.parametrize("filter_fn", FILTERS)
def test_filter_attenuates_a_single_spike(filter_fn):
    curve = np.zeros((9, 1))
    curve[4, 0] = 10.0
    out = filter_fn(curve, 3)
    assert abs(out[4, 0]) < abs(curve[4, 0])
    # far-from-spike samples are untouched by a radius-1 window
    assert out[0, 0] == 0.0
    assert out[8, 0] == 0.0


def test_median_filter_removes_a_single_spike_entirely():
    # median([0, 10, 0]) = 0, so a width-3 median kills an isolated outlier.
    curve = np.zeros((9, 1))
    curve[4, 0] = 10.0
    out = median_filter(curve, 3)
    assert out[4, 0] == 0.0


def test_moving_average_of_a_spike_is_the_window_mean():
    # (0 + 10 + 0) / 3 = 10/3, by hand.
    curve = np.zeros((9, 1))
    curve[4, 0] = 10.0
    out = moving_average_filter(curve, 3)
    assert out[4, 0] == pytest.approx(10.0 / 3.0)


@pytest.mark.parametrize("filter_fn", FILTERS)
def test_filter_keeps_the_endpoints_exactly(filter_fn):
    # The edge policy shrinks the window symmetrically, so at index 0 and at
    # index k-1 the effective radius is 0 and the point is returned unchanged.
    rng = np.random.default_rng(SEED + 10)
    curve = _random_curve(rng, 12, 2)
    for window in (3, 5, 7):
        out = filter_fn(curve, window)
        np.testing.assert_allclose(out[0], curve[0], atol=0.0)
        np.testing.assert_allclose(out[-1], curve[-1], atol=0.0)


@pytest.mark.parametrize("filter_fn", FILTERS)
def test_filter_does_not_mutate_its_input(filter_fn):
    rng = np.random.default_rng(SEED + 11)
    curve = _random_curve(rng, 10, 2)
    original = curve.copy()
    filter_fn(curve, 5)
