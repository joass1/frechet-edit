def test_erp_of_a_curve_with_itself_is_zero():
    rng = np.random.default_rng(SEED + 7)
    for k in (1, 4, 9):
        curve = _random_curve(rng, k, 2)
        assert erp(curve, curve) == pytest.approx(0.0, abs=1e-12)
        assert erp(curve, curve, g=curve.mean(axis=0)) == pytest.approx(0.0, abs=1e-12)


def test_erp_is_symmetric():
    for a, b in RANDOM_PAIRS:
        d = a.shape[1]
        for gap in (None, np.full(d, 2.5), np.concatenate([a, b]).mean(axis=0)):
            assert erp(a, b, gap) == pytest.approx(erp(b, a, gap), rel=0.0, abs=1e-12)


def test_erp_satisfies_the_triangle_inequality_on_random_triples():
    # ERP is a metric when the base distance is; L2 is, so this must hold.
    rng = np.random.default_rng(SEED + 8)
    for _ in range(15):
        d = int(rng.integers(1, 4))
        a = _random_curve(rng, int(rng.integers(1, 6)), d)
        b = _random_curve(rng, int(rng.integers(1, 6)), d)
        c = _random_curve(rng, int(rng.integers(1, 6)), d)
        assert erp(a, c) <= erp(a, b) + erp(b, c) + 1e-9


def test_erp_rejects_a_gap_point_of_the_wrong_dimension():
    a = np.array([[0.0, 0.0], [1.0, 1.0]])
    b = np.array([[0.0, 0.0]])
    with pytest.raises(ValueError):
        erp(a, b, g=np.array([0.0, 0.0, 0.0]))
    with pytest.raises(ValueError):
        erp(a, b, g=np.array([0.0, np.nan]))


