# --------------------------------------------------------------------------


def _enumerate_couplings(m: int, n: int):
    """Yield every legal coupling of an m-point and an n-point curve.

    A coupling starts at (0, 0), ends at (m-1, n-1) and advances the first
    index, the second index, or both, by one at each step. This enumerates the
    paths outright; it builds no table and applies no recurrence.
    """
    path = [(0, 0)]

    def walk(i: int, j: int):
        if i == m - 1 and j == n - 1:
            yield tuple(path)
            return
        for di, dj in ((1, 0), (0, 1), (1, 1)):
            ni, nj = i + di, j + dj
            if ni < m and nj < n:
                path.append((ni, nj))
                yield from walk(ni, nj)
                path.pop()

    yield from walk(0, 0)


def _brute_discrete_frechet(a: np.ndarray, b: np.ndarray) -> float:
    """Minimum over all couplings of the maximum coupled distance."""
    best = math.inf
    for coupling in _enumerate_couplings(len(a), len(b)):
        cost = max(float(np.linalg.norm(a[i] - b[j])) for i, j in coupling)
        if cost < best:
            best = cost
    return best


def _pointwise_distances(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    return np.sqrt(np.sum((a - b) ** 2, axis=1))


def _densify(curve: np.ndarray, k: int) -> np.ndarray:
    """Insert `k-1` evenly spaced interior samples into every segment.

    Densifying turns the CONTINUOUS problem into a discrete one: as the sample
    spacing `h` shrinks, `discrete_frechet` of the densified curves squeezes
    down onto the continuous Frechet distance from above, and it is bounded by
    `continuous_frechet + h`. This gives a check on the Alt-Godau code that
    shares no line of reasoning with it.
    """
    points = [curve[0]]
    for i in range(len(curve) - 1):
        step = (curve[i + 1] - curve[i]) / k
        for t in range(1, k + 1):
            points.append(curve[i] + step * t)
    return np.array(points, dtype=np.float64)


def _max_step(curve: np.ndarray) -> float:
    return float(np.max(np.sqrt(np.sum(np.diff(curve, axis=0) ** 2, axis=1))))


def _shared_endpoint_pairs(count: int = 12):
    """Curve pairs that share both endpoints, so the optimum is interior.

    With the endpoints pinned at the same points, the endpoint lower bound is 0
    and the value is decided by the middle of the curves - exactly the regime
    where continuous and discrete Frechet come apart.
    """
    rng = np.random.default_rng(SEED + 13)
    start = np.zeros(2)
    end = np.array([10.0, 0.0])
    centre = np.array([5.0, 0.0])
    pairs = []
    for _ in range(count):
        m = int(rng.integers(1, 4))
        n = int(rng.integers(1, 4))
        a = np.vstack([start, rng.normal(scale=2.0, size=(m, 2)) + centre, end])
        b = np.vstack([start, rng.normal(scale=2.0, size=(n, 2)) + centre, end])
        pairs.append((a, b))
    return pairs


SHARED_ENDPOINT_PAIRS = _shared_endpoint_pairs()


def _random_curve(rng: np.random.Generator, k: int, d: int) -> np.ndarray:
    return rng.normal(scale=3.0, size=(k, d)).astype(np.float64)


def _random_pairs(count: int = 20, max_k: int = 7, dims=(1, 2, 3)):
    rng = np.random.default_rng(SEED)
    pairs = []
    for _ in range(count):
        d = int(rng.choice(dims))
        m = int(rng.integers(1, max_k + 1))
        n = int(rng.integers(1, max_k + 1))
        pairs.append((_random_curve(rng, m, d), _random_curve(rng, n, d)))
    return pairs


RANDOM_PAIRS = _random_pairs()


