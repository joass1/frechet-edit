# --- DTW, worked by hand -------------------------------------------------
#
# CASE 1.  A = [0], [1], [2]   B = [0], [2]   (1-D, Euclidean = |.|)
#   local cost matrix d(i, j) = |A_i - B_j|
#        B0=0  B1=2
#   A0=0   0     2
#   A1=1   1     1
#   A2=2   2     0
#   accumulated D(i,j) = d(i,j) + min(D(i-1,j), D(i,j-1), D(i-1,j-1)):
#   D(0,0) = 0
#   D(0,1) = D(0,0) + 2 = 2
#   D(1,0) = D(0,0) + 1 = 1
#   D(1,1) = 1 + min(D(0,0)=0, D(0,1)=2, D(1,0)=1) = 1 + 0 = 1
#   D(2,0) = D(1,0) + 2 = 3
#   D(2,1) = 0 + min(D(1,0)=1, D(1,1)=1, D(2,0)=3) = 0 + 1 = 1
#   => dtw = 1.0
#   Path length: the minimum at (2,1) is a tie between the diagonal (1,0) and
#   (1,1); the documented tie-break takes the DIAGONAL, i.e. (1,0), whose own
#   path is (0,0) -> (1,0), length 2. So the chosen path is
#   (0,0), (1,0), (2,1), length 3, and dtw_normalized = 1/3.
#
# CASE 2.  A = (0,0), (3,4)    B = (0,0), (0,0), (3,4)   (2-D)
#   d(A0,B0) = 0, d(A0,B1) = 0, d(A0,B2) = 5
#   d(A1,B0) = 5, d(A1,B1) = 5, d(A1,B2) = 0
#   D(0,0) = 0 ; D(0,1) = 0 + 0 = 0 ; D(0,2) = 0 + 5 = 5
#   D(1,0) = 0 + 5 = 5
#   D(1,1) = 5 + min(D(0,0)=0, D(0,1)=0, D(1,0)=5) = 5
#   D(1,2) = 0 + min(D(0,1)=0, D(0,2)=5, D(1,1)=5) = 0
#   => dtw = 0.0 ; the chosen path is (0,0), (0,1), (1,2), length 3, so
#   dtw_normalized = 0/3 = 0.0.
#
# CASE 3.  A = [0], [10]   B = [0], [5], [10]
#   d(A0,B0)=0, d(A0,B1)=5, d(A0,B2)=10, d(A1,B0)=10, d(A1,B1)=5, d(A1,B2)=0
#   D(0,0)=0 ; D(0,1)=5 ; D(0,2)=15
#   D(1,0)=0+10=10
#   D(1,1)=5+min(D(0,0)=0, D(0,1)=5, D(1,0)=10)=5
#   D(1,2)=0+min(D(0,1)=5, D(0,2)=15, D(1,1)=5)=5   (tie: diagonal (0,1) wins)
#   => dtw = 5.0 ; chosen predecessor (0,1) has path (0,0),(0,1) of length 2,
#   so the path is (0,0), (0,1), (1,2), length 3 and dtw_normalized = 5/3.

